#!/usr/bin/env python3
"""
Embeds the web UI assets into a C translation unit.

Usage: embed_assets.py <output.c> <asset-dir>
"""
import os
import sys

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
}

# Request path -> file on disk. Order matters only for readability.
WANTED = [
    ("/index.html", "index.html"),
    ("/app.js", "app.js"),
    ("/style.css", "style.css"),
]


def emit_bytes(data):
    lines = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + " ".join("0x%02x," % b for b in chunk))
    return "\n".join(lines) if lines else "    0x00"


def main():
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    out_c, asset_dir = sys.argv[1], sys.argv[2]

    parts = [
        "/* Generated by tools/embed_assets.py - do not edit. */",
        '#include "assets.h"',
        "",
    ]

    symbols = []
    for route, filename in WANTED:
        full = os.path.join(asset_dir, filename)
        if not os.path.isfile(full):
            print(f"missing asset: {full}", file=sys.stderr)
            return 1
        with open(full, "rb") as f:
            data = f.read()
        sym = "asset_" + filename.replace(".", "_")
        symbols.append((route, sym, filename, len(data)))
        ext = os.path.splitext(filename)[1].lower()
        parts.append(f"static const unsigned char {sym}[] = {{")
        parts.append(emit_bytes(data))
        parts.append("};")
        parts.append("")

    parts.append("static const asset_t k_assets[] = {")
    for route, sym, filename, size in symbols:
        mime = MIME.get(os.path.splitext(filename)[1].lower(), "application/octet-stream")
        parts.append(f'    {{ "{route}", "{mime}", {sym}, {size} }},')
    parts.append("};")
    parts.append("")
    parts.append("const asset_t *")
    parts.append("asset_find(const char *path) {")
    parts.append("    size_t i;")
    parts.append("    if(!path) return 0;")
    parts.append("    for(i = 0; i < sizeof(k_assets) / sizeof(k_assets[0]); i++) {")
    parts.append('        if(strcmp(k_assets[i].path, path) == 0) return &k_assets[i];')
    parts.append("    }")
    parts.append("    /* The root serves the main document. */")
    parts.append('    if(strcmp(path, "/") == 0) return &k_assets[0];')
    parts.append("    return 0;")
    parts.append("}")
    parts.append("")

    os.makedirs(os.path.dirname(out_c) or ".", exist_ok=True)
    with open(out_c, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))
    # strcmp needs string.h for the generated lookup.
    with open(out_c, "r", encoding="utf-8") as f:
        text = f.read()
    text = text.replace('#include "assets.h"', '#include <string.h>\n\n#include "assets.h"', 1)
    with open(out_c, "w", encoding="utf-8") as f:
        f.write(text)

    print(f"wrote {out_c} ({len(symbols)} assets)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
